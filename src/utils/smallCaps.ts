// Стилизация UI-текста мелкими капителями по спеке abc.txt.
// ВАЖНО: применять только к статичным UI-подписям (заголовки, вкладки,
// метки), НИКОГДА к декомпилированному коду (CodeView) - там нужен
// обычный моноширинный текст без искажений для читаемости/копирования.
const MAP: Record<string, string> = {
  й: "й", ц: "ц", у: "у",
  к: "ᴋ", е: "ᴇ", н: "н", г: "ᴦ", ш: "ɯ", щ: "щ", з: "з", х: "х",
  ъ: "ɸ", ы: "ы", в: "ʙ", а: "ᴀ", п: "ᴨ", р: "ᴩ", о: "о", л: "ᴧ",
  д: "д", ж: "ж", э: "϶", я: "я", ч: "ч", с: "ᴄ", м: "ʍ", и: "и",
  т: "ᴛ", ь: "ь", б: "б", ю: "ю",
  q: "ǫ", w: "ᴡ", e: "ᴇ", r: "ʀ", t: "ᴛ", y: "ʏ", u: "ᴜ", i: "ɪ",
  o: "ᴏ", p: "ᴘ", a: "ᴀ", s: "s", d: "ᴅ", f: "ꜰ", g: "ɢ", h: "ʜ",
  j: "ᴊ", k: "ᴋ", l: "ʟ", z: "ᴢ", x: "x", c: "ᴄ", v: "ᴠ", b: "ʙ",
  n: "ɴ", m: "ᴍ",
};

export function smallCaps(text: string): string {
  return text
    .split("")
    .map(ch => MAP[ch.toLowerCase()] ?? ch)
    .join("");
}
