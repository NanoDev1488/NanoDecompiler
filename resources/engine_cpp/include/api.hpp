// api.hpp - порт resources/engine/api.py (HANDOFF_46): режим API для
// интеграции с чужими приложениями по HTTP или разовым JSON-вызовом.
//
// ОГОВОРКА ПРО HTTP-СЕРВЕР: написан на голых POSIX-сокетах (POSIX: Linux/
// macOS) с отдельной веткой на WinSock2 (Windows, см. #ifdef _WIN32 в
// api.cpp) - без внешних библиотек, как и оригинал (Python stdlib
// `http.server`). Проверено запросами через `curl` в песочнице сессии
// (только POSIX-путь, Linux) - см. HANDOFF_46. WinSock2-ветка НЕ
// протестирована (нет доступа к Windows в песочнице) - написана по тем же
// принципам и должна работать, но живьём не проверялась.
//
// Отличие от ThreadingHTTPServer (python): здесь тоже поток на соединение
// (std::thread + detach), НЕ пул потоков - при реальной нагрузке (много
// одновременных запросов) это менее эффективно, чем настоящий пул, но для
// локального инструмента (обычно один клиент - Electron GUI или соседний
// процесс на той же машине) этого достаточно, как и было достаточно
// оригиналу с тем же самым подходом (ThreadingHTTPServer тоже создаёт
// поток на каждое соединение, не пул).
#pragma once

#include <string>

namespace nd {

// --json-output: разовый вызов, печатает ТОЛЬКО JSON в stdout, возвращает
// код завершения процесса (0 = success, 1 = error) - вызывающий код
// (cli_main.cpp) должен сам вызвать std::exit с этим кодом.
int run_json_output(const std::string& jar_path, const std::string& out_dir, bool skip_legitimacy = false);

// --api-server: блокирующий вызов (как и оригинал - serve_forever()),
// возвращается только при ошибке биндинга сокета (порт занят и т.п.) - в
// этом случае возвращает false и печатает причину в stderr. Ctrl+C
// (SIGINT) снаружи останавливает процесс целиком, как и в оригинале - это
// НЕ per-функция поведение, сама функция не ловит сигналы отдельно (тот же
// эффект достигается тем, что accept() прерывается при завершении процесса).
bool run_api_server(const std::string& host, int port);

}  // namespace nd
